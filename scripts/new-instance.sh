#!/usr/bin/env bash
# Create a new per-server env file under deployments/
# Usage:
#   bash scripts/new-instance.sh --domain stream.example.com --email you@example.com
#   bash scripts/new-instance.sh --domain stream.example.com --email you@example.com \
#        --ssh-host 1.2.3.4 --allow-ip 5.6.7.8
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DOMAIN=""
EMAIL=""
SSH_HOST=""
SSH_USER="root"
ALLOW_IP=""
OUT=""

rand() { openssl rand -hex 24; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain) DOMAIN="${2:?}"; shift 2 ;;
    --email) EMAIL="${2:?}"; shift 2 ;;
    --ssh-host) SSH_HOST="${2:?}"; shift 2 ;;
    --ssh-user) SSH_USER="${2:?}"; shift 2 ;;
    --allow-ip) ALLOW_IP="${2:?}"; shift 2 ;;
    --out) OUT="${2:?}"; shift 2 ;;
    -h|--help)
      sed -n '2,8p' "$0"
      exit 0
      ;;
    *)
      echo "Unknown arg: $1" >&2
      exit 1
      ;;
  esac
done

: "${DOMAIN:?--domain is required}"
: "${EMAIL:?--email is required}"

OUT="${OUT:-$ROOT/deployments/${DOMAIN}.env}"
if [[ -f "$OUT" ]]; then
  echo "Refusing to overwrite existing $OUT" >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT")"

cat > "$OUT" <<EOF
# BH-Icecast instance — ${DOMAIN}
# Generated by scripts/new-instance.sh — do not commit

BH_DOMAIN=${DOMAIN}
ICECAST_HOSTNAME=${DOMAIN}
BH_PUBLIC_LISTEN_BASE=https://${DOMAIN}

ICECAST_SOURCE_PASSWORD=$(rand)
ICECAST_RELAY_PASSWORD=$(rand)
ICECAST_ADMIN_USER=admin
ICECAST_ADMIN_PASSWORD=$(rand)

BH_API_TOKEN=$(rand)
BH_API_ALLOW_IPS=${ALLOW_IP}

LETSENCRYPT_EMAIL=${EMAIL}

DEPLOY_SSH_HOST=${SSH_HOST}
DEPLOY_SSH_USER=${SSH_USER}
DEPLOY_REMOTE_DIR=/opt/bh-icecast
EOF

chmod 600 "$OUT"
echo "Wrote $OUT"
echo
echo "Next:"
echo "  1. Point DNS A/AAAA for ${DOMAIN} to the server"
if [[ -n "$ALLOW_IP" ]]; then
  echo "  2. (optional) edit BH_API_ALLOW_IPS in the env file"
fi
echo "  3. bash scripts/deploy-instance.sh --env $OUT"
