from __future__ import annotations

import os
import re
from pathlib import Path
from xml.sax.saxutils import escape

from sqlalchemy import select
from sqlalchemy.orm import Session

SHARED = Path(os.getenv("BH_ICECAST_SHARED", "/shared"))
MOUNTS_FILE = SHARED / "mounts.xml"
RELOAD_FLAG = SHARED / "reload"


def _xml_password(password: str) -> str:
    return escape(password, {"\"": "&quot;", "'": "&apos;"})


def sync_mounts_to_icecast(db: Session) -> None:
    """
    Write per-mount source passwords for Icecast and ask the Icecast
    container to SIGHUP (reload config without dropping active sources).
    """
    from app.models import Mount

    SHARED.mkdir(parents=True, exist_ok=True)
    mounts = db.scalars(select(Mount).where(Mount.enabled.is_(True)).order_by(Mount.name)).all()

    parts: list[str] = ["<!-- generated by BH-Icecast API — do not edit -->\n"]
    for m in mounts:
        if not m.password_plain:
            continue
        name = m.name if m.name.startswith("/") else f"/{m.name}"
        # Icecast rejects odd mount names; keep conservative
        if not re.match(r"^/[A-Za-z0-9._-]+$", name):
            continue
        title = escape(m.title or name.lstrip("/"))
        parts.append(
            f"""  <mount>
    <mount-name>{escape(name)}</mount-name>
    <password>{_xml_password(m.password_plain)}</password>
    <stream-name>{title}</stream-name>
    <public>0</public>
  </mount>
"""
        )

    MOUNTS_FILE.write_text("".join(parts), encoding="utf-8")
    RELOAD_FLAG.write_text("1", encoding="utf-8")
